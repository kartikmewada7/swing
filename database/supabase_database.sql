create extension if not exists pgcrypto;

-- -----------------------------
-- 1. PROFILES
-- auth.users is managed by Supabase Auth.
-- This table stores public profile information.
-- -----------------------------
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null default '',
    email text,
    phone text,
    created_at timestamptz not null default now()
);

alter table public.profiles
add column if not exists phone text;

-- -----------------------------
-- 2. CATEGORIES
-- -----------------------------
create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    created_at timestamptz not null default now()
);

-- -----------------------------
-- 3. FOOD ITEMS
-- -----------------------------
create table if not exists public.food_items (
    id bigint generated by default as identity primary key,
    category_id bigint references public.categories(id) on delete set null,
    name text not null,
    description text,
    price numeric(10, 2) not null check (price >= 0),
    image_url text,
    is_available boolean not null default true,
    created_at timestamptz not null default now()
);

-- -----------------------------
-- 4. CART ITEMS
-- -----------------------------
create table if not exists public.cart_items (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    food_id bigint not null references public.food_items(id) on delete cascade,
    quantity integer not null default 1 check (quantity > 0),
    created_at timestamptz not null default now(),
    unique (user_id, food_id)
);

-- -----------------------------
-- 5. ORDERS
-- -----------------------------
create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    customer_name text not null,
    phone text not null,
    address text not null,
    payment_method text not null default 'COD',
    total_amount numeric(10, 2) not null check (total_amount >= 0),
    status text not null default 'Placed',
    created_at timestamptz not null default now()
);

-- -----------------------------
-- 6. ORDER ITEMS
-- -----------------------------
create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders(id) on delete cascade,
    food_id bigint references public.food_items(id) on delete set null,
    food_name text not null,
    price numeric(10, 2) not null,
    quantity integer not null check (quantity > 0),
    created_at timestamptz not null default now()
);

-- -----------------------------
-- 7. AUTOMATIC PROFILE CREATION
-- -----------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (
        id,
        full_name,
        email,
        phone
    )
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        new.email,
        coalesce(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict (id) do nothing;

    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

-- -----------------------------
-- 8. ROW LEVEL SECURITY
-- -----------------------------
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.food_items enable row level security;
alter table public.cart_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
on public.profiles
for select
to authenticated
using (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
on public.profiles
for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists "Everyone can view categories" on public.categories;
create policy "Everyone can view categories"
on public.categories
for select
to anon, authenticated
using (true);

drop policy if exists "Everyone can view food" on public.food_items;
create policy "Everyone can view food"
on public.food_items
for select
to anon, authenticated
using (true);

drop policy if exists "Users can view own cart" on public.cart_items;
create policy "Users can view own cart"
on public.cart_items
for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can add own cart" on public.cart_items;
create policy "Users can add own cart"
on public.cart_items
for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update own cart" on public.cart_items;
create policy "Users can update own cart"
on public.cart_items
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete own cart" on public.cart_items;
create policy "Users can delete own cart"
on public.cart_items
for delete
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can view own orders" on public.orders;
create policy "Users can view own orders"
on public.orders
for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can create own orders" on public.orders;
create policy "Users can create own orders"
on public.orders
for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can view own order items" on public.order_items;
create policy "Users can view own order items"
on public.order_items
for select
to authenticated
using (
    exists (
        select 1
        from public.orders
        where public.orders.id = public.order_items.order_id
        and public.orders.user_id = auth.uid()
    )
);

drop policy if exists "Users can create own order items" on public.order_items;
create policy "Users can create own order items"
on public.order_items
for insert
to authenticated
with check (
    exists (
        select 1
        from public.orders
        where public.orders.id = public.order_items.order_id
        and public.orders.user_id = auth.uid()
    )
);

